#!/usr/bin/env node
/**
 * README extension and plugin lists, generated from their own metadata.
 *
 * Writes the list of extensions (extensions/<id>/extension.json: name,
 * category, description) and plugins (plugins/<dir>/package.json:
 * seedhtmlPlugin.name and the package description) between marker comments in
 * README.md, so a new extension or plugin is listed without anyone
 * remembering to. Better README text comes from improving the description in
 * the extension's or plugin's own metadata, which the app shows too.
 *
 *   node scripts/readme-extensions.mjs           rewrite README.md
 *   node scripts/readme-extensions.mjs --check   fail if README.md is stale
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as prettier from 'prettier';

const root = process.cwd();
const readmePath = join(root, 'README.md');
const START =
  '<!-- extensions:start (generated by npm run readme:extensions; edit the descriptions in extension.json / package.json) -->';
const END = '<!-- extensions:end -->';

// Section order and headings. An extension without a category is a source
// format when it supplies a chapter template, otherwise a library for
// transform scripts.
const GROUPS = [
  ['format', 'Source formats'],
  ['code-blocks', 'Code blocks'],
  ['chapter-content', 'Chapter content'],
  ['typesetting', 'Typesetting and layout'],
  ['accessibility', 'Accessibility'],
  ['library', 'Libraries for transform scripts'],
];
const KNOWN = new Set(GROUPS.map(([key]) => key));

/** @param {string} dir */
const subdirs = dir =>
  readdirSync(join(root, dir), { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort();

/** One line of text: manifests may wrap, the list may not. */
const oneLine = text => String(text).replace(/\s+/g, ' ').trim();

const extensions = subdirs('extensions').map(dir => {
  const manifest = JSON.parse(
    readFileSync(join(root, 'extensions', dir, 'extension.json'), 'utf8')
  );
  const group = manifest.category ?? (manifest.chapter ? 'format' : 'library');
  if (!KNOWN.has(group)) {
    throw new Error(
      `readme-extensions: extensions/${dir} has unknown category "${group}" — add it to GROUPS`
    );
  }
  if (!manifest.name || !manifest.description) {
    throw new Error(
      `readme-extensions: extensions/${dir}/extension.json needs a name and a description`
    );
  }
  return { dir, group, name: manifest.name, description: oneLine(manifest.description) };
});

const plugins = subdirs('plugins').flatMap(dir => {
  let pkg;
  try {
    pkg = JSON.parse(readFileSync(join(root, 'plugins', dir, 'package.json'), 'utf8'));
  } catch {
    return []; // not a package
  }
  if (!pkg.seedhtmlPlugin) return [];
  if (!pkg.seedhtmlPlugin.name || !pkg.description) {
    throw new Error(
      `readme-extensions: plugins/${dir}/package.json needs seedhtmlPlugin.name and a description`
    );
  }
  return [{ dir, name: pkg.seedhtmlPlugin.name, description: oneLine(pkg.description) }];
});

/** @param {{ name: string, description: string }} item @param {string} path */
const bullet = (item, path) => `- **[${item.name}](${path})**: ${item.description}`;

const lines = [START, ''];
for (const [key, heading] of GROUPS) {
  const members = extensions
    .filter(extension => extension.group === key)
    .sort((a, b) => a.name.localeCompare(b.name));
  if (members.length === 0) continue;
  lines.push(`#### ${heading}`, '');
  for (const extension of members) lines.push(bullet(extension, `extensions/${extension.dir}/`));
  lines.push('');
}
lines.push('### Plugins', '');
for (const plugin of plugins.sort((a, b) => a.name.localeCompare(b.name))) {
  lines.push(bullet(plugin, `plugins/${plugin.dir}/`));
}
lines.push('', END);
const block = lines.join('\n');

const readme = readFileSync(readmePath, 'utf8');
const startAt = readme.indexOf(START);
const endAt = readme.indexOf(END);
if (startAt === -1 || endAt === -1 || endAt < startAt) {
  throw new Error(
    'readme-extensions: README.md lacks the extensions:start / extensions:end markers'
  );
}
// Formatted as format:check would leave it, so --check agrees with Prettier
// (it escapes characters such as the * in a description's `lang-*`).
const updated = await prettier.format(
  readme.slice(0, startAt) + block + readme.slice(endAt + END.length),
  { ...(await prettier.resolveConfig(readmePath)), filepath: readmePath }
);

if (process.argv.includes('--check')) {
  if (updated !== readme) {
    console.error('readme-extensions: README.md is out of date — run `npm run readme:extensions`');
    process.exit(1);
  }
  console.log(
    `readme-extensions: README.md lists ${extensions.length} extensions and ${plugins.length} plugins`
  );
} else {
  writeFileSync(readmePath, updated);
  console.log(
    `readme-extensions: wrote ${extensions.length} extensions and ${plugins.length} plugins to README.md`
  );
}
